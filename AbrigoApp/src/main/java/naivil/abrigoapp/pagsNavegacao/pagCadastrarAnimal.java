    private void buttonCadastrarAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonCadastrarAnimalActionPerformed
        String nome = fieldNome.getText().trim();
        String raca = fieldRaca.getText().trim();
        if(nome.isEmpty() || raca.isEmpty()){
            JOptionPane.showMessageDialog(this, "Preencha o nome e a raça.");
            return;
        }
        
        int idade;
        try {
            idade = Integer.parseInt(fieldIdade.getText().trim());
            if(idade < 0) {throw new NumberFormatException();}
        } catch (NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Insira uma idade válida.");
        }
        
        java.time.LocalDate data;
        try{
            java.time.format.DateTimeFormatter fmt = java.time.format.DateTimeFormatter.ofPattern("dd/MM/uuuu").withResolverStyle(java.time.format.ResolverStyle.STRICT);
            data = java.time.LocalDate.parse(fieldData.getText().trim(), fmt);
        } catch (java.time.format.DateTimeParseException ex) {
            JOptionPane.showMessageDialog(this, "Data de resgate inválida.");
        }
        
        if(data.isAfter(java.time.LocalDate.now())){
            JOptionPane.showMessageDialog(this, "Data inválida.");
            return;
        }
        
        String dataResgate = fieldData.getText().trim();
        
        new Animais(nome, (String) boxEspecie.getSelectedItem(), raca, idade, (String) boxPorte.getSelectedItem(), (String) boxSaude.getSelectedItem(), dataResgate, (String) boxAdocao.getSelectedItem());
        
        JOptionPane.showMessageDialog(this, "Animal cadastrado.");
        telaAnimais.atualizarTabela();
        telaAnimais.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_buttonCadastrarAnimalActionPerformed

