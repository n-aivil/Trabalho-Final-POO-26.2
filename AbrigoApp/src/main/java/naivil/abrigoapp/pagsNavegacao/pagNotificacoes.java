    private void iniciarAtualizacao() {
        javax.Swing.Timer timer = new javax.Swing.Timer(5000, e -> {

            new SwingWorker<java.util.List<Notificacao>, Void>() {
                @Override
                protected java.util.List<Notificacao> doInBackground() {
                    return buscarNotificacoes();
                }

                @Override
                protected void done() {
                    try {
                        for (Notificacao n : get()){
                            modelo.add(0, n);
                        }
                        if (modelo.size() > 50){
                            modelo.setSize(50);
                        }
                    } catch(InterruptedException | ExecutionException ex) {}
                }
            }.execute();
        });
        timer.start();
    }

    private java.util.List<Notificacao> buscarNotificacoes(){
        java.util.List<Notificacao> lista = new java.util.ArrayList<>();
        lista.add(new Notificacao("Titulo", "Mensagem da notif"));
        return lista;
    }
