    private void buttonCriarAtividadeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonCriarAtividadeActionPerformed
        String titulo = fieldTituloAtividade.getText().trim();
        if(titulo.isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe o título da atividade");
            return;
        }
        
        java.time.LocalDate data = null;
        try{
            java.time.format.DateTimeFormatter fmt = java.time.format.DateTimeFormatter.ofPattern("dd/MM/uuuu").withResolverStyle(java.time.format.ResolverStyle.STRICT);
            data = java.time.LocalDate.parse(fieldData.getText().trim(), fmt);
        } catch (java.time.format.DateTimeParseException ex){
            JOptionPane.showMessageDialog(this, "Data inválida.");
        }
        
        modelo.addElement(new Atividade(titulo, fieldDescricao.getText().trim(), data));
        
        telaAtividades.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_buttonCriarAtividadeActionPerformed

